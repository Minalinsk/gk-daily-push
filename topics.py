def tag_of(title):
    """返回这条标题最贴合的考点名；一个都没命中就返回空串。"""
    title = title or ""
    best, best_hits = "", 0
    for name, kws in TOPICS:
        hits = sum(1 for k in kws if k in title)
        if hits > best_hits:      # 严格大于：命中数相同时保留靠前的考点
            best, best_hits = name, hits
    return best


def tag_all(items):
    """给条目列表就地挂上 topic 字段（空串表示没打上标签）。"""
    for it in items:
        it["topic"] = tag_of(it.get("title", ""))
    return items
